--5 RESERVAS
CREATE TABLE RESERVA (
    ID_RESERVA INT IDENTITY(1,1) PRIMARY KEY,
    ID_HUESPED INT NOT NULL,
    ID_HABITACION INT NOT NULL,
    ID_CANAL INT NOT NULL,
    FECHA_RESERVA DATETIME DEFAULT GETDATE(),
    FECHA_INGRESO_PROGRAMADA DATE NOT NULL,
    FECHA_SALIDA_PROGRAMADA DATE NOT NULL,
    NUMERO_PERSONAS INT NOT NULL,
    ESTADO_RESERVA VARCHAR(20) DEFAULT 'Pendiente',
    CONSTRAINT FK_RESERVA_HUESPED
    FOREIGN KEY (ID_HUESPED)
    REFERENCES HUESPED(ID_HUESPED),
    CONSTRAINT FK_RESERVA_HABITACION
    FOREIGN KEY (ID_HABITACION)
    REFERENCES HABITACION(ID_HABITACION),
    CONSTRAINT FK_RESERVA_CANAL
    FOREIGN KEY (ID_CANAL)
    REFERENCES CANAL_RESERVA(ID_CANAL),
    CONSTRAINT CK_RESERVA_FECHAS
    CHECK (FECHA_SALIDA_PROGRAMADA > FECHA_INGRESO_PROGRAMADA),
    CONSTRAINT CK_RESERVA_PERSONAS
    CHECK (NUMERO_PERSONAS > 0),
    CONSTRAINT CK_RESERVA_ESTADO
    CHECK (ESTADO_RESERVA IN
    ('Pendiente', 'Confirmada', 'Cancelada', 'Finalizada'))
);
GO

