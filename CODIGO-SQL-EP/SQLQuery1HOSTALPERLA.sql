--15. CURSOR PARA RECORRER LOS PAGOS POR ESTADIA
DECLARE @idEstadia INT;
DECLARE @totalPagado DECIMAL(10,2);

-- DECLARAR EL CURSOR
DECLARE cursor_Pagos CURSOR LOCAL FAST_FORWARD
FOR
    SELECT
        ID_ESTADIA,
        SUM(MONTO) AS TOTAL_PAGADO
    FROM PAGO
    WHERE ESTADO_PAGO = 'Registrado'
    GROUP BY ID_ESTADIA
    ORDER BY ID_ESTADIA;

-- ABRIR EL CURSOR
OPEN cursor_Pagos;

-- OBTENER EL PRIMER REGISTRO
FETCH NEXT FROM cursor_Pagos
INTO @idEstadia, @totalPagado;

-- RECORRER LOS REGISTROS
WHILE @@FETCH_STATUS = 0
BEGIN

    PRINT CONCAT(
        'Estadia: ', @idEstadia,
        ' | Total pagado: S/ ',
        @totalPagado
    );
    FETCH NEXT FROM cursor_Pagos
    INTO @idEstadia, @totalPagado;
END;

-- CERRAR EL CURSOR
CLOSE cursor_Pagos;

-- LIBERAR EL CURSOR
DEALLOCATE cursor_Pagos;
GO


